param(
  [string]$InstallDir = "$env:LOCALAPPDATA\MediaForge-Homologacao",
  [string]$RepoUrl = "https://github.com/thiagopantoja0911-netizen/media-forge.git",
  [string]$Branch = "feature/mediaforge-artistic-director-20261115",
  [string]$ServerUrl = "https://mediaforge-staging.salevo.site"
)
$ErrorActionPreference = "Stop"
$taskName = "MediaForge Worker - Homologacao"
$InstallDir = [IO.Path]::GetFullPath($InstallDir)
# The existing "MediaForge Worker - Staging" task may use the production endpoint.
if ($ServerUrl -ne "https://mediaforge-staging.salevo.site") {
  throw "O worker de homologacao so pode acessar mediaforge-staging.salevo.site."
}
if ($InstallDir -eq [IO.Path]::GetFullPath("$env:LOCALAPPDATA\MediaForge-Staging") -or $InstallDir -eq [IO.Path]::GetFullPath("$env:LOCALAPPDATA\MediaForge-Staging-V2")) {
  throw "Diretorio ocupado por instalacao anterior. Use MediaForge-Homologacao."
}
if (Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue) {
  throw "Tarefa de homologacao ja existe. Nenhuma tarefa existente sera modificada."
}
$health = Invoke-RestMethod -Method Get -Uri ($ServerUrl + "/health") -TimeoutSec 20
if (-not $health.ok -or $health.service -ne "mediaforge-orchestrator") {
  throw "O staging nao respondeu como MediaForge. Nada foi instalado."
}
$node = Get-Command node -ErrorAction SilentlyContinue
if (-not $node -or ((& node --version).Trim() -notmatch "^v(2[2-9]|[3-9][0-9])\.")) {
  throw "Node.js 22 ou superior e necessario."
}
if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
  throw "Git nao encontrado."
}
if (Test-Path -LiteralPath $InstallDir) {
  if (-not (Test-Path -LiteralPath (Join-Path $InstallDir ".git"))) {
    throw "A pasta ja existe e nao e um clone Git. Nenhum arquivo sera sobrescrito."
  }
  $existingRemote = (& git -C $InstallDir remote get-url origin).Trim()
  if ($existingRemote -ne $RepoUrl) { throw "Repositorio diferente; abortando." }
  & git -C $InstallDir fetch origin $Branch
  if ($LASTEXITCODE -ne 0) { throw "Falha no git fetch." }
  & git -C $InstallDir checkout $Branch
  if ($LASTEXITCODE -ne 0) { throw "Falha no git checkout." }
  & git -C $InstallDir pull --ff-only origin $Branch
  if ($LASTEXITCODE -ne 0) { throw "Branch local divergente; abortando." }
} else {
  & git clone --branch $Branch --single-branch $RepoUrl $InstallDir
  if ($LASTEXITCODE -ne 0) { throw "Falha no git clone." }
}
Push-Location $InstallDir
try {
  & npm install --ignore-scripts
  if ($LASTEXITCODE -ne 0) { throw "Falha no npm install." }
} finally { Pop-Location }
# An exclusive token is generated by the staging admin. Never reuse a production token.
$secure = Read-Host "Cole o token EXCLUSIVO criado no staging (nao envie no chat)" -AsSecureString
$ptr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
try {
  $token = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($ptr)
  if ($token.Length -lt 32) { throw "Token muito curto; nenhuma credencial foi gravada." }
  $response = Invoke-RestMethod -Uri ($ServerUrl + "/v1/worker/auth-check") -Method Post -ContentType "application/json" -Headers @{Authorization = ("Bearer " + $token)} -Body "{}" -TimeoutSec 20
  if (-not $response.ok -or -not $response.authenticated) { throw "Falha no preflight de autenticacao." }
} finally {
  Remove-Variable -Name token -ErrorAction SilentlyContinue
  [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($ptr)
}
$stateDir = Join-Path $InstallDir ".mediaforge"
$tokenPath = Join-Path $stateDir "worker-token.dpapi"
$envPath = Join-Path $InstallDir ".env.local"
if ((Test-Path -LiteralPath $tokenPath) -or (Test-Path -LiteralPath $envPath)) {
  throw "Configuracao ou token ja existe na pasta. Nada sera sobrescrito."
}
New-Item -ItemType Directory -Force -Path $stateDir | Out-Null
$sid = [Security.Principal.WindowsIdentity]::GetCurrent().User.Value
$cipher = $secure | ConvertFrom-SecureString
[IO.File]::WriteAllText($tokenPath, $cipher, (New-Object Text.UTF8Encoding($false)))
& icacls $tokenPath /inheritance:r /grant:r ('*' + $sid + ':(F)') | Out-Null
if ($LASTEXITCODE -ne 0) { throw "Nao foi possivel restringir permissoes do token DPAPI." }
$settings = @(
  "MEDIAFORGE_REMOTE_URL=$ServerUrl",
  "MEDIAFORGE_WORKER_ID=$env:COMPUTERNAME-homologacao",
  "MEDIAFORGE_PROJECTS_DIR=.mediaforge/projects",
  "MEDIAFORGE_RENDERER=hyperframes",
  "MEDIAFORGE_POLL_MS=4000"
)
[IO.File]::WriteAllLines($envPath, [string[]]$settings, (New-Object Text.UTF8Encoding($false)))
& icacls $envPath /inheritance:r /grant:r ('*' + $sid + ':(F)') | Out-Null
if ($LASTEXITCODE -ne 0) { throw "Nao foi possivel restringir permissoes do ambiente." }
$runner = Join-Path $InstallDir "desktop\run-worker.ps1"
$launcher = Join-Path $InstallDir "desktop\launch-worker-hidden.vbs"
if (-not (Test-Path -LiteralPath $runner) -or -not (Test-Path -LiteralPath $launcher)) {
  throw "Componentes do worker nao encontrados."
}
$wscript = Join-Path $env:SystemRoot "System32\wscript.exe"
$arguments = '//B //Nologo "' + $launcher + '" "' + $runner + '" "' + $InstallDir + '"'
$action = New-ScheduledTaskAction -Execute $wscript -Argument $arguments -WorkingDirectory $InstallDir
$userId = [Security.Principal.WindowsIdentity]::GetCurrent().Name
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $userId
$principal = New-ScheduledTaskPrincipal -UserId $userId -LogonType Interactive -RunLevel Limited
$taskSettings = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit ([TimeSpan]::Zero)
$taskSettings.Hidden = $true
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Principal $principal -Settings $taskSettings -Description "MediaForge homologacao isolada; sem acesso a fila de producao." | Out-Null
Start-ScheduledTask -TaskName $taskName
Write-Output "Worker de homologacao instalado isoladamente."
Write-Output "Servidor: $ServerUrl"
Write-Output "Tarefa: $taskName"
Write-Output "Diretorio: $InstallDir"
